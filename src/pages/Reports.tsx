import React, { useState } from 'react';
import { FileText, Download, Printer, Calendar, Eye, Info } from 'lucide-react';
import { useApp } from '../context/AppContext';

export default function Reports() {
  const { profile, symptoms, cycleEntries, wellnessEntries } = useApp();
  const [dateFrom, setDateFrom] = useState(() => {
    const d = new Date();
    d.setMonth(d.getMonth() - 1);
    return d.toISOString().split('T')[0];
  });
  const [dateTo, setDateTo] = useState(new Date().toISOString().split('T')[0]);
  const [includeCycle, setIncludeCycle] = useState(true);
  const [includeWellness, setIncludeWellness] = useState(true);
  const [showPreview, setShowPreview] = useState(false);

  const filteredSymptoms = symptoms.filter(s => {
    const d = new Date(s.date);
    return d >= new Date(dateFrom) && d <= new Date(dateTo + 'T23:59:59');
  });

  const filteredCycle = cycleEntries.filter(e => {
    const d = new Date(e.startDate);
    return d >= new Date(dateFrom) && d <= new Date(dateTo + 'T23:59:59');
  });

  const filteredWellness = wellnessEntries.filter(w => {
    const d = new Date(w.date);
    return d >= new Date(dateFrom) && d <= new Date(dateTo + 'T23:59:59');
  });

  const avgSeverity = filteredSymptoms.length > 0
    ? (filteredSymptoms.reduce((s, e) => s + e.severity, 0) / filteredSymptoms.length).toFixed(1)
    : 'N/A';

  const symptomSummary: Record<string, number> = {};
  filteredSymptoms.forEach(s => { symptomSummary[s.name] = (symptomSummary[s.name] || 0) + 1; });

  const avgMood = filteredWellness.length > 0
    ? (filteredWellness.reduce((s, w) => s + w.mood, 0) / filteredWellness.length).toFixed(1)
    : 'N/A';
  const avgSleep = filteredWellness.length > 0
    ? (filteredWellness.reduce((s, w) => s + w.sleepHours, 0) / filteredWellness.length).toFixed(1)
    : 'N/A';

  const generateReportText = () => {
    let report = `HEALTH SUMMARY REPORT\n`;
    report += `Generated: ${new Date().toLocaleDateString()}\n`;
    report += `Patient: ${profile?.name || 'User'}\n`;
    report += `Reporting Period: ${new Date(dateFrom).toLocaleDateString()} to ${new Date(dateTo).toLocaleDateString()}\n`;
    report += `${'='.repeat(50)}\n\n`;

    report += `SYMPTOM HISTORY\n`;
    report += `${'-'.repeat(30)}\n`;
    report += `Total entries: ${filteredSymptoms.length}\n`;
    report += `Average severity: ${avgSeverity}/10\n\n`;

    if (Object.keys(symptomSummary).length > 0) {
      report += `Symptom Frequency:\n`;
      Object.entries(symptomSummary).sort((a, b) => b[1] - a[1]).forEach(([name, count]) => {
        report += `  • ${name}: ${count} occurrence(s)\n`;
      });
      report += '\n';
    }

    report += `Detailed Entries:\n`;
    filteredSymptoms.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()).forEach(s => {
      report += `  ${new Date(s.date).toLocaleDateString()} - ${s.name} (Severity: ${s.severity}/10)`;
      if (s.duration) report += `, Duration: ${s.duration}`;
      if (s.notes) report += ` - "${s.notes}"`;
      report += '\n';
    });

    if (includeCycle && profile?.cycleTracking) {
      report += `\n\nMENSTRUAL CYCLE HISTORY\n`;
      report += `${'-'.repeat(30)}\n`;
      if (filteredCycle.length > 0) {
        filteredCycle.forEach(e => {
          report += `  Period: ${new Date(e.startDate).toLocaleDateString()}`;
          if (e.endDate) report += ` to ${new Date(e.endDate).toLocaleDateString()}`;
          if (e.symptoms.length > 0) report += ` | Symptoms: ${e.symptoms.join(', ')}`;
          report += '\n';
        });
      } else {
        report += `  No cycle entries in this period.\n`;
      }
    }

    if (includeWellness) {
      report += `\n\nWELLNESS OVERVIEW\n`;
      report += `${'-'.repeat(30)}\n`;
      report += `  Entries logged: ${filteredWellness.length}\n`;
      report += `  Average mood: ${avgMood}/10\n`;
      report += `  Average sleep: ${avgSleep} hours\n`;
    }

    report += `\n\n${'='.repeat(50)}\n`;
    report += `NOTES FOR DOCTOR VISIT\n`;
    report += `${'-'.repeat(30)}\n`;
    report += `This report contains user-logged observations only.\n`;
    report += `It is not a medical diagnosis or assessment.\n`;
    report += `Please discuss these observations with your healthcare provider.\n`;
    report += `\nGenerated by HERA Health Companion\n`;
    report += `This tool does not provide medical advice.\n`;

    return report;
  };

  const handleDownload = () => {
    const text = generateReportText();
    const blob = new Blob([text], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `HERA_Health_Report_${dateFrom}_to_${dateTo}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    const text = generateReportText();
    const printWindow = window.open('', '_blank');
    if (printWindow) {
      printWindow.document.write(`<html><head><title>HERA Health Report</title><style>body{font-family:system-ui;padding:40px;line-height:1.6;white-space:pre-wrap;}</style></head><body>${text}</body></html>`);
      printWindow.document.close();
      printWindow.print();
    }
  };

  return (
    <div className="max-w-4xl mx-auto animate-fade-in">
      <div className="mb-8">
        <h1 className="text-2xl sm:text-3xl font-bold text-gray-900">Health Reports</h1>
        <p className="text-gray-600 mt-1">Generate a summary of your health data for doctor visits.</p>
      </div>

      {/* Configuration */}
      <div className="bg-white rounded-2xl border border-gray-100 p-6 mb-6">
        <h3 className="font-semibold text-gray-900 mb-4">Report Settings</h3>
        <div className="grid sm:grid-cols-2 gap-4 mb-4">
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">From Date</label>
            <input type="date" value={dateFrom} onChange={e => setDateFrom(e.target.value)}
              className="w-full px-4 py-2.5 rounded-xl border border-gray-200 focus:border-lavender-400" />
          </div>
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">To Date</label>
            <input type="date" value={dateTo} onChange={e => setDateTo(e.target.value)}
              className="w-full px-4 py-2.5 rounded-xl border border-gray-200 focus:border-lavender-400" />
          </div>
        </div>
        <div className="space-y-3">
          <label className="flex items-center gap-3 cursor-pointer">
            <input type="checkbox" checked={includeCycle} onChange={e => setIncludeCycle(e.target.checked)}
              className="w-4 h-4 rounded accent-lavender-500" />
            <span className="text-sm text-gray-700">Include menstrual cycle data</span>
          </label>
          <label className="flex items-center gap-3 cursor-pointer">
            <input type="checkbox" checked={includeWellness} onChange={e => setIncludeWellness(e.target.checked)}
              className="w-4 h-4 rounded accent-lavender-500" />
            <span className="text-sm text-gray-700">Include wellness data (mood, sleep, energy)</span>
          </label>
        </div>
      </div>

      {/* Summary */}
      <div className="bg-white rounded-2xl border border-gray-100 p-6 mb-6">
        <h3 className="font-semibold text-gray-900 mb-4">Report Summary</h3>
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
          <div className="bg-lavender-50 rounded-xl p-3 text-center">
            <p className="text-2xl font-bold text-lavender-700">{filteredSymptoms.length}</p>
            <p className="text-xs text-gray-500">Symptoms</p>
          </div>
          <div className="bg-rose-warm-50 rounded-xl p-3 text-center">
            <p className="text-2xl font-bold text-rose-warm-500">{avgSeverity}</p>
            <p className="text-xs text-gray-500">Avg Severity</p>
          </div>
          <div className="bg-amber-50 rounded-xl p-3 text-center">
            <p className="text-2xl font-bold text-amber-700">{avgMood}</p>
            <p className="text-xs text-gray-500">Avg Mood</p>
          </div>
          <div className="bg-indigo-50 rounded-xl p-3 text-center">
            <p className="text-2xl font-bold text-indigo-700">{avgSleep}h</p>
            <p className="text-xs text-gray-500">Avg Sleep</p>
          </div>
        </div>
      </div>

      {/* Actions */}
      <div className="flex flex-wrap gap-3 mb-6">
        <button
          onClick={() => setShowPreview(!showPreview)}
          className="flex items-center gap-2 px-5 py-2.5 bg-lavender-600 text-white rounded-xl font-medium hover:bg-lavender-700 transition-colors"
        >
          <Eye className="w-4 h-4" />
          {showPreview ? 'Hide Preview' : 'Preview Report'}
        </button>
        <button
          onClick={handleDownload}
          className="flex items-center gap-2 px-5 py-2.5 border border-gray-200 text-gray-700 rounded-xl hover:bg-gray-50 transition-colors"
        >
          <Download className="w-4 h-4" />
          Download
        </button>
        <button
          onClick={handlePrint}
          className="flex items-center gap-2 px-5 py-2.5 border border-gray-200 text-gray-700 rounded-xl hover:bg-gray-50 transition-colors"
        >
          <Printer className="w-4 h-4" />
          Print
        </button>
      </div>

      {/* Preview */}
      {showPreview && (
        <div className="bg-white rounded-2xl border border-gray-100 p-6 animate-fade-in">
          <pre className="text-sm text-gray-700 whitespace-pre-wrap font-mono leading-relaxed">
            {generateReportText()}
          </pre>
        </div>
      )}

      {/* Disclaimer */}
      <div className="mt-6 flex items-start gap-3 p-4 bg-lavender-50 rounded-xl">
        <Info className="w-5 h-5 text-lavender-600 flex-shrink-0 mt-0.5" />
        <p className="text-sm text-lavender-800">
          <strong>Note:</strong> This report contains only data you have logged. It distinguishes your observations from any generated summaries. It does not include medical diagnoses or fabricated records. Share this with your healthcare provider as a conversation starter.
        </p>
      </div>
    </div>
  );
}
